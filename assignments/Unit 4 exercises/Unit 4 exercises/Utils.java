public class Utils {
    public static String intArrayToString(int[] arr){
        String output = "";
        for(int i: arr){
            output += i;
        }
        return output;
    }
    public static String stringArrayToString(String[] arr){
        String output = "";
        for(String i: arr){
            output += i;
        }
        return output;
    }
}
